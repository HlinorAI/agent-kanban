#!/bin/bash
# Install Kanban.app (macOS): opens the dashboard in a Chrome --app window and
# refreshes repo facts in the background on every launch. Optional scheduled
# hidden refresh via LaunchAgent: ./install-macos.sh --with-schedule
#
# Usage: ./install-macos.sh [--with-schedule] [--html /path/to/kanban.html]
# HTML default: next to this script's kanban.html, else ~/kanban.html.
set -euo pipefail

HTML="${KANBAN_HTML:-}"
SCHEDULE=0
while [ $# -gt 0 ]; do
  case "$1" in
    --with-schedule) SCHEDULE=1; shift ;;
    --html) HTML="$2"; shift 2 ;;
    *) echo "unknown arg: $1"; exit 2 ;;
  esac
done

HERE="$(cd "$(dirname "$0")" && pwd)"
if [ -z "$HTML" ]; then
  if [ -f "$HERE/kanban.html" ]; then HTML="$HERE/kanban.html";
  elif [ -f "$HOME/kanban/kanban.html" ]; then HTML="$HOME/kanban/kanban.html";
  elif [ -f "$HOME/kanban.html" ]; then HTML="$HOME/kanban.html";
  else HTML="$HOME/kanban/kanban.html"
       echo "Board not found yet — defaulting to $HTML; first launch will run the setup wizard."
  fi
fi
CHROME="/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
[ -x "$CHROME" ] || CHROME=""
APP_SRC="$HERE/macos/Kanban.app"
TARGET="/Applications/ProjectKanban.app"
[ -w /Applications ] 2>/dev/null || TARGET="$HOME/Applications/ProjectKanban.app"

mkdir -p "$APP_SRC/Contents/MacOS"
cat > "$APP_SRC/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleName</key><string>ProjectKanban</string>
	<key>CFBundleDisplayName</key><string>Project Kanban</string>
	<key>CFBundleIdentifier</key><string>io.github.agent-kanban</string>
	<key>CFBundleVersion</key><string>1.0.0</string>
	<key>CFBundlePackageType</key><string>APPL</string>
	<key>CFBundleExecutable</key><string>kanban-launcher</string>
	<key>LSUIElement</key><true/>
	<key>NSHighResolutionCapable</key><true/>
</dict>
</plist>
EOF
cat > "$APP_SRC/Contents/MacOS/kanban-launcher" <<EOF
#!/bin/bash
# Generated by install-macos.sh — agent-kanban
LOG="\$HOME/Library/Logs/kanban-app.log"
HTML="$HTML"
UPDATER="$HERE/kanban-update.py"
PY="\${KANBAN_PYTHON:-/usr/bin/python3}"
ts() { date '+%Y-%m-%d %H:%M:%S'; }
echo "[\$(ts)] launch args: \${*:-<none>}" >> "\$LOG"
if [ ! -f "\$HTML" ]; then
  echo "[\$(ts)] board not found at \$HTML — opening first-run wizard" >> "\$LOG"
  open "$HERE/macos-first-run.command"
  exit 0
fi
if [ "\${1:-}" != "--update-only" ]; then
  if [ -n "$CHROME" ]; then
    nohup "$CHROME" --app="file://\$HTML" >>"\$LOG" 2>&1 &
    echo "[\$(ts)] dashboard opened: Chrome --app" >> "\$LOG"
  else
    open "\$HTML"
    echo "[\$(ts)] dashboard opened: default browser" >> "\$LOG"
  fi
fi
echo "[\$(ts)] updater started" >> "\$LOG"
"\$PY" "\$UPDATER" "\$HTML" >> "\$LOG" 2>&1
rc=\$?
echo "[\$(ts)] updater finished rc=\$rc" >> "\$LOG"
exit \$rc
EOF
chmod +x "$APP_SRC/Contents/MacOS/kanban-launcher"
cat > "$HERE/macos-first-run.command" <<EOF
#!/bin/bash
# Generated by install-macos.sh — agent-kanban first run
echo "agent-kanban: first run — repository discovery"
/usr/bin/python3 "$HERE/kanban-setup.py" --target "\$HOME/kanban"
[ -f "\$HOME/kanban/kanban.html" ] && open "\$HOME/kanban/kanban.html"
EOF
chmod +x "$HERE/macos-first-run.command"
plutil -lint "$APP_SRC/Contents/Info.plist"
rm -rf "$TARGET"
cp -R "$APP_SRC" "$TARGET"
# Ad-hoc signing is required for macOS to attribute TCC access requests to the
# app: an unsigned bundle gets SILENT denials (no prompt, not listed under
# Files & Folders) when the updater touches ~/Documents.
xattr -cr "$TARGET" 2>/dev/null || true
if codesign --force --deep -s - "$TARGET" 2>/dev/null; then
  echo "Code signing: ad-hoc signature applied."
else
  echo "WARNING: ad-hoc codesign failed. If macOS never shows a Documents access prompt, add the app to Full Disk Access manually."
fi
echo "Installed: $TARGET"
echo "First launch: double-click ProjectKanban.app; allow Documents access when macOS asks (one time)."

if [ "$SCHEDULE" -eq 1 ]; then
  PLIST="$HOME/Library/LaunchAgents/io.github.agent-kanban.update.plist"
  cat > "$PLIST" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>Label</key><string>io.github.agent-kanban.update</string>
	<key>ProgramArguments</key>
	<array>
		<string>/usr/bin/open</string>
		<string>-g</string>
		<string>$TARGET</string>
		<string>--args</string>
		<string>--update-only</string>
	</array>
	<key>RunAtLoad</key><true/>
	<key>StartCalendarInterval</key>
	<dict>
		<key>Hour</key><integer>9</integer>
		<key>Minute</key><integer>0</integer>
	</dict>
	<key>StandardOutPath</key><string>$HOME/Library/Logs/kanban-app.log</string>
	<key>StandardErrorPath</key><string>$HOME/Library/Logs/kanban-app.log</string>
</dict>
</plist>
EOF
  UID_N=$(id -u)
  launchctl bootout "gui/$UID_N/io.github.agent-kanban.update" 2>/dev/null || true
  launchctl bootstrap "gui/$UID_N" "$PLIST"
  echo "Scheduled: login + daily 09:00 (LaunchAgent io.github.agent-kanban.update)."
fi
